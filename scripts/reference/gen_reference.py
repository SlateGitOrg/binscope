#!/usr/bin/env python3
"""Produce tests/reference/*.tsv with the real reference tools.

usage (from the repo root):
    TOOLS=$(scripts/reference/build_tools.sh)
    cargo run --release --example gen_synth -- "$TOOLS/synth"
    "$TOOLS/venv/bin/python" scripts/reference/gen_reference.py "$TOOLS"

Outputs (all names are repo-relative fixture paths or synth/<name>):
    ssdeep_hashes.tsv   name, digest                  (ssdeep 2.14.1 -s -c)
    tlsh_hashes.tsv     name, digest | TNULL           (TLSH 4.12.1)
    ssdeep_compare.tsv  name_a, name_b, score          (libfuzzy fuzzy_compare)
    tlsh_diff.tsv       name_a, name_b, diff, diff_xlen (Tlsh::totalDiff)
    pefile.tsv          name, imphash, section, raw_size, entropy (pefile)
    sections.tsv        name, section, offset, size, address (llvm-readobj; ELF, Mach-O)
    imports.tsv         name, comma-joined sorted undefined symbols (llvm-nm; ELF, Mach-O)

llvm-readobj / llvm-nm come from the Rust toolchain's llvm-tools component
(`rustup component add llvm-tools`); set LLVM_BIN to override.
"""
import csv
import itertools
import os
import random
import subprocess
import sys
from pathlib import Path

import json
import re

import pefile

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "tests" / "reference"


def run(args, **kw):
    return subprocess.run(args, check=True, capture_output=True, text=True, **kw).stdout


def main() -> None:
    tools = Path(sys.argv[1]).resolve()
    synth_dir = tools / "synth"
    fixtures = sorted((REPO / "fixtures" / "bin").glob("*/*"))
    synth = sorted(synth_dir.iterdir())
    names = {p: f"synth/{p.name}" for p in synth}
    names.update({p: str(p.relative_to(REPO)) for p in fixtures})
    files = synth + fixtures
    OUT.mkdir(parents=True, exist_ok=True)
    header = "# generated by scripts/reference/gen_reference.py with ssdeep 2.14.1, TLSH 4.12.1, pefile 2024.8.26\n"

    # --- digests ------------------------------------------------------------
    ss = {}
    for row in csv.reader(run([tools / "ssdeep", "-s", "-c", *files]).splitlines()[1:]):
        ss[Path(row[1]).resolve()] = row[0]
    tl = {}
    for line in run([tools / "tlshref", "hash", *files]).splitlines():
        h, p = line.split("\t")
        tl[Path(p).resolve()] = h
    with open(OUT / "ssdeep_hashes.tsv", "w") as f:
        f.write(header)
        for p in files:
            # ssdeep -s skips empty files; libfuzzy digests them as "3::".
            f.write(f"{names[p]}\t{ss.get(p.resolve(), '3::')}\n")
    with open(OUT / "tlsh_hashes.tsv", "w") as f:
        f.write(header)
        for p in files:
            f.write(f"{names[p]}\t{tl[p.resolve()]}\n")

    # --- pairs --------------------------------------------------------------
    pairs = []
    by_base = {}
    for p in synth:
        parts = p.name.split("-")
        base = "-".join(parts[:3])
        by_base.setdefault(base, []).append(p)
    for group in by_base.values():
        group.sort(key=lambda q: q.name)
        pairs += [(group[0], q) for q in group[1:]]
        pairs += list(zip(group[1:], group[2:]))
    by_target = {}
    for p in fixtures:
        by_target.setdefault(p.parent.name, []).append(p)
    for group in by_target.values():
        pairs += list(itertools.combinations(group, 2))
    rng = random.Random(6)
    pairs += [tuple(rng.sample(fixtures, 2)) for _ in range(300)]

    with open(OUT / "ssdeep_compare.tsv", "w") as f:
        f.write(header)
        for a, b in pairs:
            ha, hb = ss.get(a.resolve(), "3::"), ss.get(b.resolve(), "3::")
            score = run([tools / "fuzzyref", "cmp", ha, hb]).strip()
            f.write(f"{names[a]}\t{names[b]}\t{score}\n")
    with open(OUT / "tlsh_diff.tsv", "w") as f:
        f.write(header)
        for a, b in pairs:
            ha, hb = tl[a.resolve()], tl[b.resolve()]
            if "TNULL" in (ha, hb):
                continue
            d, x = run([tools / "tlshref", "diff", ha, hb]).split()
            f.write(f"{names[a]}\t{names[b]}\t{d}\t{x}\n")

    # --- pefile ---------------------------------------------------------------
    with open(OUT / "pefile.tsv", "w") as f:
        f.write(header)
        for p in fixtures:
            if p.suffix != ".exe":
                continue
            pe = pefile.PE(str(p))
            imph = pe.get_imphash() or "-"
            for s in pe.sections:
                name = s.Name.rstrip(b"\0").decode()
                f.write(f"{names[p]}\t{imph}\t{name}\t{s.SizeOfRawData}\t{s.get_entropy():.12f}\n")
    # --- llvm-readobj / llvm-nm (ELF and single-arch Mach-O) ----------------
    llvm = Path(os.environ.get("LLVM_BIN") or next(
        Path(run(["rustc", "--print", "sysroot"]).strip()).glob("lib/rustlib/*/bin/llvm-readobj")).parent)
    native = [p for p in fixtures if p.parent.name.startswith(("elf-", "macho-")) and p.parent.name != "macho-universal"]
    with open(OUT / "sections.tsv", "w") as f:
        f.write(header.replace("pefile 2024.8.26", "llvm-readobj (Rust llvm-tools)"))
        for p in native:
            if p.parent.name.startswith("elf-"):
                doc = json.loads(run([llvm / "llvm-readobj", "--elf-output-style=JSON", "--sections", p]))
                for item in doc[0]["Sections"]:
                    s = item["Section"]
                    if s["Type"]["Name"] == "SHT_NULL":
                        continue
                    size = 0 if s["Type"]["Name"] == "SHT_NOBITS" else s["Size"]
                    f.write(f"{names[p]}\t{s['Name']['Name']}\t{s['Offset']}\t{size}\t{s['Address']}\n")
            else:
                text = run([llvm / "llvm-readobj", "--sections", p])
                for block in text.split("Section {")[1:]:
                    sect = re.search(r"Name: (\S+)", block).group(1)
                    seg = re.search(r"Segment: (\S+)", block).group(1)
                    addr = int(re.search(r"Address: (0x[0-9A-Fa-f]+)", block).group(1), 16)
                    size = int(re.search(r"Size: (0x[0-9A-Fa-f]+)", block).group(1), 16)
                    off = int(re.search(r"Offset: (\d+)", block).group(1))
                    zerofill = re.search(r"Type: (ZeroFill|GBZeroFill|ThreadLocalZerofill)", block)
                    f.write(f"{names[p]}\t{seg},{sect}\t{off}\t{0 if zerofill or off == 0 else size}\t{addr}\n")
    with open(OUT / "imports.tsv", "w") as f:
        f.write(header.replace("pefile 2024.8.26", "llvm-nm (Rust llvm-tools)"))
        for p in native:
            flags = ["-D", "--undefined-only"] if p.parent.name.startswith("elf-") else ["--undefined-only"]
            syms = sorted({line.split()[-1] for line in run([llvm / "llvm-nm", *flags, p]).splitlines() if line.strip()})
            f.write(f"{names[p]}\t{','.join(syms)}\n")
    print(f"{len(files)} files, {len(pairs)} pairs -> {OUT}")


if __name__ == "__main__":
    main()
