#!/usr/bin/env python3
"""Regenerate src/hashes/ordinals.rs from pefile's ordlookup tables.

binscope's imphash must match pefile's get_imphash(), which resolves
import-by-ordinal entries for ws2_32.dll / wsock32.dll / oleaut32.dll through
these tables (and emits "ord<N>" otherwise). The tables are factual
DLL-ordinal-to-name mappings shipped with pefile (MIT licence).

usage: python gen_ordinals.py > src/hashes/ordinals.rs   (needs pefile installed)
"""
import ordlookup  # provided by the pefile package

HEADER = """//! Ordinal-to-name tables for DLLs that are commonly imported by ordinal.
//!
//! Generated by `scripts/gen_ordinals.py` from pefile's `ordlookup` package
//! (MIT licence, see DATA.md). Do not edit by hand.

#![allow(clippy::unreadable_literal)]

/// One `(ordinal, name)` table, sorted by ordinal for binary search.
pub type OrdinalTable = &'static [(u16, &'static str)];
"""


def main() -> None:
    print(HEADER)
    for dll, table in sorted(ordlookup.ords.items()):
        ident = dll.decode().split(".")[0].upper()
        print(f"/// Ordinal names for `{dll.decode()}`.")
        print(f"pub const {ident}: OrdinalTable = &[")
        for ordinal in sorted(table):
            print(f'    ({ordinal}, "{table[ordinal].decode()}"),')
        print("];\n")
    print("/// Look up the table for a (lower-cased, full) DLL name such as `ws2_32.dll`.")
    print("pub fn table_for(dll_lower: &str) -> Option<OrdinalTable> {")
    print("    match dll_lower {")
    for dll in sorted(ordlookup.ords):
        ident = dll.decode().split(".")[0].upper()
        print(f'        "{dll.decode()}" => Some({ident}),')
    print("        _ => None,")
    print("    }")
    print("}")


if __name__ == "__main__":
    main()
