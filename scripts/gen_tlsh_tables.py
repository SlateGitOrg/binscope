#!/usr/bin/env python3
"""Regenerate src/fuzzy/tlsh_tables.rs from the TLSH reference source.

TLSH's published description (Oliver, Cheng & Chen, 2013) fixes the algorithm
but two constant tables have to match the reference implementation bit for
bit: the Pearson permutation `v_table` and the `topval` length-bucket bounds
used by l_capturing(). Both are copied verbatim from trendmicro/tlsh
(Apache-2.0 OR BSD-3-Clause, see DATA.md).

usage: python gen_tlsh_tables.py path/to/tlsh-4.12.1 > src/fuzzy/tlsh_tables.rs
"""
import re
import sys
from pathlib import Path


def c_array(src: str, name: str) -> list[int]:
    m = re.search(name + r"\s*\[\d*\]\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit(f"array {name} not found")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return [int(tok, 0) for tok in re.findall(r"0x[0-9a-fA-F]+|\d+", body)]


def main() -> None:
    root = Path(sys.argv[1])
    impl = (root / "src" / "tlsh_impl.cpp").read_text()
    util = (root / "src" / "tlsh_util.cpp").read_text()
    v_table = c_array(impl, r"static unsigned char v_table")
    topval = c_array(util, r"unsigned int topval")
    assert len(v_table) == 256 and sorted(v_table) == list(range(256)), "v_table must be a permutation"
    assert len(topval) == 170 and topval == sorted(topval), "topval must be 170 ascending bounds"
    print("//! Constant tables for TLSH, copied from the reference implementation")
    print("//! (trendmicro/tlsh 4.12.1, Apache-2.0 OR BSD-3-Clause; see DATA.md).")
    print("//! Generated by `scripts/gen_tlsh_tables.py`. Do not edit by hand.\n")
    print("/// Pearson-hash permutation of 0..=255 used by TLSH's bucket mapping.")
    print("pub const V_TABLE: [u8; 256] = [")
    for i in range(0, 256, 16):
        print("    " + ", ".join(str(v) for v in v_table[i : i + 16]) + ",")
    print("];\n")
    print("/// Upper bounds of the 170 log-scaled length buckets (`l_capturing`).")
    print("pub const TOPVAL: [u32; 170] = [")
    for i in range(0, 170, 8):
        print("    " + ", ".join(str(v) for v in topval[i : i + 8]) + ",")
    print("];")


if __name__ == "__main__":
    main()
