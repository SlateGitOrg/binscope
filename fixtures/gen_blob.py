#!/usr/bin/env python3
"""Generate fixtures/src blob headers for the plainblob / packed families.

usage: gen_blob.py VARIANT {plain|packed} OUT_HEADER

The text is deterministic (fixed word list + LCG seeded by VARIANT), so the
corpus rebuilds byte-for-byte. 'packed' stores zlib level-9 output of the
same text, which is what drives the entropy contrast binscope reports.
"""
import sys
import zlib

WORDS = (
    "binary section header import export symbol entropy table string offset "
    "loader segment relocation linker archive object module library runtime "
    "triage analyst sample corpus fuzzy digest bucket quartile cluster rule "
    "capability evidence report window rolling block signature checksum"
).split()


def text(variant: int, size: int = 24 * 1024) -> bytes:
    state = 0x2545F491 ^ (variant * 0x9E3779B9 & 0xFFFFFFFF)
    out = []
    n = 0
    while n < size:
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        w = WORDS[(state >> 8) % len(WORDS)]
        out.append(w)
        n += len(w) + 1
    return (" ".join(out)[:size]).encode()


def main() -> None:
    variant, mode, out = int(sys.argv[1]), sys.argv[2], sys.argv[3]
    data = text(variant)
    if mode == "packed":
        data = zlib.compress(data, 9)
    elif mode != "plain":
        raise SystemExit("mode must be plain or packed")
    lines = [
        "/* generated by gen_blob.py - do not edit */",
        f"#define BS_BLOB_LEN {len(data)}",
        "BS_BLOB_SECTION static const unsigned char bs_blob[BS_BLOB_LEN] = {",
    ]
    for i in range(0, len(data), 16):
        lines.append("  " + ",".join(str(b) for b in data[i : i + 16]) + ",")
    lines.append("};")
    with open(out, "w", encoding="ascii") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
